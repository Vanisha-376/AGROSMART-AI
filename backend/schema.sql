CREATE DATABASE IF NOT EXISTS agrosmart_ai;
USE agrosmart_ai;
CREATE TABLE IF NOT EXISTS sensor_readings (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 device_id VARCHAR(80) NOT NULL DEFAULT 'ESP32-01',
 moisture DECIMAL(5,2) NOT NULL,
 temperature DECIMAL(5,2) NULL,
 humidity DECIMAL(5,2) NULL,
 pump_on BOOLEAN NOT NULL DEFAULT FALSE,
 water_used_liters DECIMAL(10,2) NOT NULL DEFAULT 0,
 source ENUM('hardware','demo') NOT NULL DEFAULT 'hardware',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_created_at(created_at)
);
CREATE TABLE IF NOT EXISTS irrigation_events (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 event_type VARCHAR(40) NOT NULL DEFAULT 'NOTE',
 message VARCHAR(255) NOT NULL,
 moisture DECIMAL(5,2) NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS irrigation_settings (
 id INT PRIMARY KEY,
 start_threshold DECIMAL(5,2) NOT NULL DEFAULT 30,
 stop_threshold DECIMAL(5,2) NOT NULL DEFAULT 45,
 auto_mode BOOLEAN NOT NULL DEFAULT TRUE,
 max_pump_seconds INT NOT NULL DEFAULT 20,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
